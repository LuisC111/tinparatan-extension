import { isLight, safeColor, withAlpha } from "./color.js";
import { fontFamily } from "./fonts.js";

export function applyThemeVars(settings, root = document.documentElement) {
  const theme = settings.theme;
  const bg = settings.background.type === "solid" ? settings.background.color : theme.background;
  const style = root.style;
  const set = (name, value) => style.setProperty(name, value);
  set("--bg", safeColor(bg, "#070b14"));
  set("--accent", safeColor(theme.accent, "#e11d2e"));
  set("--on-accent", isLight(theme.accent) ? "#1a090c" : "#ffffff");
  set("--text", safeColor(theme.text, "#f5f7fb"));
  set("--muted", safeColor(theme.muted, "#93a0b5"));
  set("--surface", safeColor(theme.surface, "#121a2b"));
  set("--line", safeColor(theme.line, "rgba(255,255,255,0.10)"));
  set("--prompt", safeColor(theme.prompt, theme.accent));
  set("--wordmark", safeColor(theme.wordmark, "#f7f8fb"));
  set("--search-bg", safeColor(theme.searchBg, "rgba(10,14,24,0.78)"));
  set("--search-text", safeColor(theme.searchText, "#f5f7fb"));
  set("--placeholder", safeColor(theme.placeholder, "#8b97ab"));
  set("--accent-soft", withAlpha(theme.accent, 0.18));
  set("--accent-glow", withAlpha(theme.accent, 0.45));
  set("--vignette", String(theme.vignette));
  set("--logo-size", `${settings.logo.size}px`);
  set("--wm-size", `${settings.wordmark.fontSize}px`);
  set("--wm-weight", String(settings.wordmark.fontWeight));
  set("--wm-tracking", `${settings.wordmark.letterSpacing}px`);
  set("--wm-font", fontFamily(settings.wordmark.fontId));
  set("--gap", `${settings.layout.gap}px`);
  set("--offset-y", String(settings.layout.offsetY));
  set("--search-w", `${settings.search.width}px`);
  set("--cols", String(settings.shortcuts.columns));
  set("--g1", settings.background.gradient.colors[0]);
  set("--g2", settings.background.gradient.colors[1]);
  set("--g3", settings.background.gradient.colors[2]);
  set("--g-angle", `${settings.background.gradient.angle}deg`);
  set("--intensity", String(settings.background.intensity));
  set("--dim", String(settings.background.dim));
  set("--media-blur", `${settings.background.blur}px`);
  set("--media-brightness", String(settings.background.brightness));

  root.dataset.motion = settings.motion;
  root.dataset.bg = settings.background.type;
  root.dataset.effect = settings.background.effect;
  root.dataset.searchStyle = settings.search.style;
  root.dataset.glow = settings.logo.glow ? "1" : "0";
  root.dataset.float = settings.logo.float ? "1" : "0";
  root.dataset.alignX = settings.layout.alignX;
  root.dataset.alignY = settings.layout.alignY;
  root.dataset.fit = settings.background.fit;
  root.dataset.blurry = settings.background.blur > 0 ? "1" : "0";
  root.dataset.scheme = isLight(bg) ? "light" : "dark";
  root.style.colorScheme = isLight(bg) ? "light" : "dark";
  if (settings.background.type === "gradient" && settings.background.gradient.animate) root.dataset.pan = "1";
  else delete root.dataset.pan;
}
